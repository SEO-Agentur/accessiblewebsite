#!/usr/bin/env node
/**
 * Generates apps/web/src/lib/axeTranslations.ts from the scanner's axe-core
 * package + its bundled German locale file.
 *
 * Re-run this script whenever axe-core is upgraded in apps/scanner:
 *   node apps/web/scripts/build-axe-translations.mjs
 *
 * The output is a checked-in TypeScript file (no runtime axe-core dep in the
 * web app). It maps the English `help` text that the scanner stored back to
 * the rule's German `help` text from axe-core's de.json.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../../..');
const axeRoot = path.join(repoRoot, 'apps/scanner/node_modules/axe-core');

if (!fs.existsSync(axeRoot)) {
  console.error(`axe-core not found at ${axeRoot}. Run pnpm install first.`);
  process.exit(1);
}

// axe-core exposes getRules() with the English defaults.
const requireFromScanner = createRequire(pathToFileURL(path.join(axeRoot, 'package.json')));
const axe = requireFromScanner('axe-core');
const enRules = axe.getRules();

const deLocale = JSON.parse(fs.readFileSync(path.join(axeRoot, 'locales/de.json'), 'utf8'));

const enHelpToDe = new Map();
const enDescriptionToDe = new Map();
for (const r of enRules) {
  const deEntry = deLocale.rules?.[r.ruleId];
  if (!deEntry) continue;
  if (deEntry.help) enHelpToDe.set(r.help, deEntry.help);
  if (deEntry.description) enDescriptionToDe.set(r.description, deEntry.description);
}

// failureSummary prefixes (axe-core's failureSummaries block).
const failurePrefixDe = deLocale.failureSummaries ?? {};

const escape = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const helpEntries = [...enHelpToDe.entries()]
  .map(([en, de]) => `  [\`${escape(en)}\`, \`${escape(de)}\`],`)
  .join('\n');

const descEntries = [...enDescriptionToDe.entries()]
  .map(([en, de]) => `  [\`${escape(en)}\`, \`${escape(de)}\`],`)
  .join('\n');

const ts = `// AUTO-GENERATED by apps/web/scripts/build-axe-translations.mjs — do not edit.
// Source: axe-core ${axe.version} + axe-core/locales/de.json
// Re-run after upgrading axe-core in apps/scanner.

const HELP_EN_TO_DE = new Map<string, string>([
${helpEntries}
]);

const DESCRIPTION_EN_TO_DE = new Map<string, string>([
${descEntries}
]);

const FAILURE_PREFIX_DE = ${JSON.stringify(failurePrefixDe, null, 2)} as Record<string, { failureMessage?: string }>;

/**
 * Translate the English \`v.help\` text that the scanner stored in scan_issues.description
 * back to German via axe-core's bundled de.json. Falls through to the input if no mapping
 * exists (handles rules added after this table was generated).
 */
export function translateAxeHelp(en: string | null | undefined): string {
  if (!en) return '';
  return HELP_EN_TO_DE.get(en) ?? en;
}

/**
 * Same but for axe rule descriptions (longer-form sentence beneath the help).
 */
export function translateAxeDescription(en: string | null | undefined): string {
  if (!en) return '';
  return DESCRIPTION_EN_TO_DE.get(en) ?? en;
}

/**
 * The \`remediationHint\` we stored is axe-core's node.failureSummary, which is a
 * multi-line block like:
 *   Fix any of the following:
 *     - Element has insufficient color contrast of 3.5
 *     - …
 * Translate the prefix lines via failureSummaries.de; check messages are kept as
 * stored because axe doesn't expose individual check translations by stable id
 * in a way we can reverse-match a stored sentence to. Better than nothing.
 */
export function translateAxeFailureSummary(en: string | null | undefined): string {
  if (!en) return '';
  let out = en;
  for (const key of Object.keys(FAILURE_PREFIX_DE)) {
    const def = FAILURE_PREFIX_DE[key];
    if (!def?.failureMessage) continue;
    // The English equivalents that axe-core uses as the prefix lines:
    const enAny = 'Fix any of the following:';
    const enAll = 'Fix all of the following:';
    if (key === 'any') out = out.replace(enAny, def.failureMessage);
    if (key === 'all' || key === 'none') out = out.replace(enAll, def.failureMessage);
  }
  return out;
}
`;

const outPath = path.join(repoRoot, 'apps/web/src/lib/axeTranslations.ts');
fs.writeFileSync(outPath, ts);
console.log(`Wrote ${enHelpToDe.size} help + ${enDescriptionToDe.size} description mappings`);
console.log(`→ ${outPath}`);
